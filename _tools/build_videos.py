"""Update the video data in _data/videos.yml.

_data/videos.yml is the source of the video pages and may be edited by hand.
To add a video, add an entry with at least `youtube_id` and `title` to a
channel and run this script. It only adds what is missing:

- `slug` (from the title, made unique) for videos without one
- `available` (checked via YouTube oEmbed) for videos without one
- the thumbnail assets/videos/thumbs/yt-<youtube_id>.jpg (320x180 from YouTube)
  and the `thumb` path, if missing
- the video page _videos/<slug>.html; its front matter (title, date,
  description and preview image for the SEO tags) is kept in sync with
  videos.yml (the page shows the data from videos.yml)

Existing values are never changed. Video pages without an entry are reported.

Usage (needs PyYAML: pip install pyyaml):
    python _tools/build_videos.py
"""
import json
import os
import re
import sys
import urllib.error
import urllib.request

import yaml

SITE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DATA_FILE = os.path.join(SITE, "_data", "videos.yml")
PAGES_DIR = os.path.join(SITE, "_videos")
THUMBS_DIR = os.path.join(SITE, "assets", "videos", "thumbs")
# "yt-" prefix: Jekyll skips files starting with "_", and some IDs do
THUMB_URL = "/assets/videos/thumbs/yt-{}.jpg"
# Preview image for link previews (480x360, exists for every available video)
PREVIEW_URL = "https://i.ytimg.com/vi/{}/hqdefault.jpg"

HEADER = """\
# Videos (pages: /videos/ and /videos/<slug>/), grouped by channel.
# May be edited by hand. To add a video, add an entry with youtube_id and title
# and run _tools/build_videos.py; it adds slug, availability, thumbnail and page.
# author_id links the author to his forum member page (_members), if there is one.
"""

CHANNEL_KEYS = ["slug", "title", "videos"]
VIDEO_KEYS = ["slug", "youtube_id", "title", "description", "author", "author_id",
              "posted", "available", "thumb"]


def slugify(text):
    return re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-") or "video"


def fetch(url):
    """Return (status, body) of a GET request."""
    try:
        with urllib.request.urlopen(url, timeout=60) as r:
            return r.status, r.read()
    except urllib.error.HTTPError as e:
        return e.code, b""


def is_available(youtube_id):
    status, _ = fetch(f"https://www.youtube.com/oembed?url=https://www.youtube.com/watch?v={youtube_id}&format=json")
    return status == 200


def download_thumb(youtube_id):
    """Save the 320x180 thumbnail. Returns False if YouTube has none."""
    status, data = fetch(f"https://i.ytimg.com/vi/{youtube_id}/mqdefault.jpg")
    if status != 200 or not data:
        return False
    os.makedirs(THUMBS_DIR, exist_ok=True)
    with open(os.path.join(THUMBS_DIR, f"yt-{youtube_id}.jpg"), "wb") as f:
        f.write(data)
    return True


def meta_description(video, channel):
    """Description for search engines and link previews (about 160 characters)."""
    generic = (f"{video['title']}: video by {video.get('author') or 'a member'} "
               f"in the Hype Forever video gallery ({channel['title']})")
    text = " ".join((video.get("description") or "").split())
    if len(text) < 40:
        text = f"{text} – {generic}." if text else f"{generic}."
    return shorten(text, 160)


def shorten(text, limit):
    """Cut text at a word boundary and add an ellipsis if it is longer than limit."""
    if len(text) <= limit:
        return text
    return text[:limit - 1].rsplit(" ", 1)[0].rstrip(" ,;:.-–") + "…"


def iso_date(posted):
    """'2013-02-24 18:35' -> '2013-02-24T18:35:00' (as written in videos.yml)."""
    m = re.fullmatch(r"(\d{4}-\d\d-\d\d)[ T](\d\d:\d\d)(:\d\d)?", str(posted).strip())
    return f"{m.group(1)}T{m.group(2)}{m.group(3) or ':00'}" if m else str(posted)


def write_page(video, channel):
    """Create or update _videos/<slug>.html. The front matter holds what the
    SEO tags need (title, date, description, preview image), everything else
    comes from videos.yml."""
    path = os.path.join(PAGES_DIR, video["slug"] + ".html")
    lines = ["---",
             "# Generated by _tools/build_videos.py, edit _data/videos.yml instead",
             f"title: {json.dumps(video['title'], ensure_ascii=False)}"]
    if video.get("posted"):
        lines.append(f"date: {iso_date(video['posted'])}")
    lines.append(f"description: {json.dumps(meta_description(video, channel), ensure_ascii=False)}")
    if video.get("available"):
        lines += ["image:",
                  f"  path: {PREVIEW_URL.format(video['youtube_id'])}",
                  "  width: 480",
                  "  height: 360"]
    content = "\n".join(lines + ["---", ""])
    old = open(path, encoding="utf-8").read() if os.path.exists(path) else None
    if old != content:
        os.makedirs(PAGES_DIR, exist_ok=True)
        with open(path, "w", encoding="utf-8", newline="\n") as f:
            f.write(content)
        print(f"  page _videos/{video['slug']}.html {'updated' if old else 'created'}")


def ordered(entry, keys):
    """Return entry with known keys in a fixed order, unknown keys kept at the end."""
    result = {k: entry[k] for k in keys if k in entry}
    result.update({k: v for k, v in entry.items() if k not in keys})
    return result


class Dumper(yaml.SafeDumper):
    pass


def str_presenter(dumper, data):
    # Multi-line text (descriptions) as readable block scalars
    if "\n" in data:
        return dumper.represent_scalar("tag:yaml.org,2002:str", data, style="|")
    return dumper.represent_scalar("tag:yaml.org,2002:str", data)


Dumper.add_representer(str, str_presenter)


def main():
    channels = yaml.safe_load(open(DATA_FILE, encoding="utf-8")) or []
    slugs = {v["slug"] for c in channels for v in c.get("videos") or [] if v.get("slug")}

    for channel in channels:
        channel["videos"] = channel.get("videos") or []
        for video in channel["videos"]:
            if not video.get("youtube_id") or not video.get("title"):
                print(f"WARNING: entry without youtube_id or title in channel '{channel.get('slug')}'")
                continue

            if not video.get("slug"):
                base = slugify(video["title"])
                slug, n = base, 2
                while slug in slugs:
                    slug, n = f"{base}-{n}", n + 1
                video["slug"] = slug
                slugs.add(slug)
                print(f"new video: {slug}")

            if "available" not in video:
                video["available"] = is_available(video["youtube_id"])
                print(f"  {video['slug']}: {'available' if video['available'] else 'NOT available'} on YouTube")

            thumb_path = os.path.join(THUMBS_DIR, f"yt-{video['youtube_id']}.jpg")
            if not os.path.exists(thumb_path):
                if download_thumb(video["youtube_id"]):
                    print(f"  thumbnail {video['youtube_id']}.jpg")
                else:
                    print(f"  WARNING: no thumbnail for {video['slug']}")
            if os.path.exists(thumb_path) and not video.get("thumb"):
                video["thumb"] = THUMB_URL.format(video["youtube_id"])

            write_page(video, channel)

        channel["videos"] = [ordered(v, VIDEO_KEYS) for v in channel["videos"]]

    pages = {f[:-5] for f in os.listdir(PAGES_DIR) if f.endswith(".html")} if os.path.isdir(PAGES_DIR) else set()
    for orphan in sorted(pages - slugs - {v.get("slug") for c in channels for v in c["videos"]}):
        print(f"WARNING: _videos/{orphan}.html has no entry in videos.yml")

    channels = [ordered(c, CHANNEL_KEYS) for c in channels]
    with open(DATA_FILE, "w", encoding="utf-8", newline="\n") as f:
        f.write(HEADER + "\n")
        yaml.dump(channels, f, Dumper=Dumper, sort_keys=False, allow_unicode=True, width=1000)

    videos = [v for c in channels for v in c["videos"]]
    print(f"\n{len(channels)} channels, {len(videos)} videos "
          f"({sum(1 for v in videos if not v.get('available'))} not available)")


if __name__ == "__main__":
    if len(sys.argv) > 1:
        sys.exit(__doc__)
    main()
